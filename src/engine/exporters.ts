/*
 * Text exporters: CSV and Markdown. Pure functions, so the same output comes
 * from the browser and the CLI.
 */
import type { ProjectFile } from "../types";
import { buildModel, zonePath, type Model } from "./model";
import { countBySeverity, postureScore, runRules, type Finding } from "./rules";
import { buildConduits, buildRuleMatrix, buildZoneRegister, type ConduitEntry, type RuleRow, type ZoneEntry } from "./matrix";

export interface Analysis {
  model: Model;
  findings: Finding[];
  conduits: ConduitEntry[];
  zones: ZoneEntry[];
  matrix: RuleRow[];
  score: number;
}

export function analyse(project: Pick<ProjectFile, "nodes" | "edges">): Analysis {
  const model = buildModel(project.nodes, project.edges);
  const findings = runRules(model);
  const conduits = buildConduits(model);
  return {
    model,
    findings,
    conduits,
    zones: buildZoneRegister(model, conduits),
    matrix: buildRuleMatrix(model),
    score: postureScore(findings)
  };
}

export function csvCell(value: unknown): string {
  const text = value === undefined || value === null ? "" : String(value);
  // Neutralise spreadsheet formula injection and quote when needed.
  const safe = /^[=+\-@\t\r]/.test(text) ? `'${text}` : text;
  return /[",\n\r]/.test(safe) ? `"${safe.replace(/"/g, '""')}"` : safe;
}

export function toCsv(header: string[], rows: unknown[][]): string {
  return [header, ...rows].map((r) => r.map(csvCell).join(",")).join("\r\n") + "\r\n";
}

export function inventoryCsv(model: Model): string {
  const rows = [...model.assets.values()].map((a) => [
    a.data.title, a.data.assetType, a.data.category, zonePath(model, a.zoneId), a.data.ip, a.data.vlan, a.data.mac,
    a.data.purdueLevel !== undefined ? `L${a.data.purdueLevel}` : "", a.data.criticality, a.data.slCapability,
    a.data.vendor, a.data.model, a.data.firmware, a.data.protocols.join("; "), a.data.owner, a.data.status, a.data.notes
  ]);
  return toCsv(["Name", "Type", "Category", "Zone", "IP", "VLAN", "MAC", "Purdue", "Criticality", "SL-C", "Vendor", "Model", "Firmware", "Protocols", "Owner", "Status", "Notes"], rows);
}

export function matrixCsv(rows: RuleRow[]): string {
  return toCsv(
    ["#", "Source", "Source zone", "Source IP", "Destination", "Destination zone", "Destination IP", "Protocol", "Service", "Action", "Routed via", "Conduit", "Secured", "Cross-zone", "Comment"],
    rows.map((r) => [r.no, r.source, r.sourceZone, r.sourceIp, r.destination, r.destinationZone, r.destinationIp, r.protocol, r.service, "ALLOW", r.routedVia, r.conduit, r.secured ? "yes" : "no", r.crossZone ? "yes" : "no", r.comment])
  );
}

export function conduitsCsv(conduits: ConduitEntry[]): string {
  return toCsv(
    ["Conduit", "Zone A", "Zone B", "SL-T (max)", "Flows", "Protocols", "Boundary devices", "All flows protected", "Labels"],
    conduits.map((c) => [c.id, c.zoneA, c.zoneB, c.slt, c.flowCount, c.protocols.join("; "), c.boundaryDevices.join("; "), c.allProtected ? "yes" : "no", c.labels.join("; ")])
  );
}

export function zonesCsv(zones: ZoneEntry[]): string {
  return toCsv(
    ["Zone", "Path", "Type", "SL-T", "Subnet", "VLAN", "Owner", "Assets", "High/critical", "Safety", "Conduits"],
    zones.map((z) => [z.title, z.path, z.zoneType, z.slt, z.subnet, z.vlan, z.owner, z.assetCount, z.criticalCount, z.safetyCount, z.conduitCount])
  );
}

export function findingsCsv(findings: Finding[]): string {
  return toCsv(
    ["Severity", "Rule", "Category", "Title", "Detail", "Recommendation", "References"],
    findings.map((f) => [f.severity, f.ruleId, f.category, f.title, f.message, f.recommendation, f.references.join("; ")])
  );
}

const md = (v: unknown) => (v === undefined || v === null || v === "" ? "—" : String(v).replace(/\|/g, "\\|").replace(/\n/g, " "));

export function markdownReport(project: Pick<ProjectFile, "name" | "description" | "nodes" | "edges">, analysis = analyse(project)): string {
  const { model, findings, conduits, zones, matrix, score } = analysis;
  const counts = countBySeverity(findings);
  const assets = [...model.assets.values()];
  const L: string[] = [];
  L.push(`# ${project.name}`, "");
  if (project.description) L.push(project.description, "");
  L.push(`_Generated by OT Network Studio on ${new Date().toISOString().slice(0, 10)}._`, "");
  L.push("## Summary", "");
  L.push(`| Metric | Value |`, `|---|---|`);
  L.push(`| Assets | ${assets.length} |`, `| Zones | ${model.zones.size} |`, `| Conduits | ${conduits.length} |`);
  L.push(`| Flows / links | ${model.flows.length} / ${model.links.length} |`, `| Firewall rule rows | ${matrix.length} |`);
  L.push(`| Design posture score | ${score} / 100 |`);
  L.push(`| Findings | ${counts.critical} critical · ${counts.high} high · ${counts.medium} medium · ${counts.low} low · ${counts.info} info |`, "");

  L.push("## Findings", "");
  if (!findings.length) L.push("No findings.", "");
  else {
    L.push("| Severity | Rule | Finding | Recommendation |", "|---|---|---|---|");
    for (const f of findings.filter((x) => x.severity !== "info")) L.push(`| ${f.severity} | ${f.ruleId} | ${md(f.message)} | ${md(f.recommendation)} |`);
    const info = findings.filter((x) => x.severity === "info").length;
    if (info) L.push("", `_${info} informational finding(s) omitted._`);
    L.push("");
  }

  L.push("## Zone register", "");
  L.push("| Zone | Type | SL-T | Subnet | VLAN | Assets | High/critical | Safety | Conduits |", "|---|---|---|---|---|---|---|---|---|");
  for (const z of zones) L.push(`| ${md(z.path)} | ${z.zoneType} | ${md(z.slt)} | ${md(z.subnet)} | ${md(z.vlan)} | ${z.assetCount} | ${z.criticalCount} | ${z.safetyCount} | ${z.conduitCount} |`);
  L.push("");

  L.push("## Conduit register", "");
  if (!conduits.length) L.push("No cross-zone flows modelled.", "");
  else {
    L.push("| Conduit | Between | SL-T | Flows | Protocols | Boundary devices | Protected |", "|---|---|---|---|---|---|---|");
    for (const c of conduits) L.push(`| ${c.id} | ${md(c.zoneA)} ↔ ${md(c.zoneB)} | ${md(c.slt)} | ${c.flowCount} | ${md(c.protocols.join(", "))} | ${md(c.boundaryDevices.join(", ") || "none")} | ${c.allProtected ? "yes" : "no"} |`);
    L.push("");
  }

  L.push("## Firewall rule matrix", "");
  if (!matrix.length) L.push("No flows modelled.", "");
  else {
    L.push("| # | Source | Destination | Protocol | Service | Via | Comment |", "|---|---|---|---|---|---|---|");
    for (const r of matrix) L.push(`| ${r.no} | ${md(r.source)} (${md(r.sourceIp)}, ${md(r.sourceZone)}) | ${md(r.destination)} (${md(r.destinationIp)}, ${md(r.destinationZone)}) | ${md(r.protocol)} | ${md(r.service)} | ${md(r.routedVia)} | ${md(r.comment)} |`);
    L.push("");
  }

  L.push("## Asset inventory", "");
  L.push("| Asset | Type | Zone | IP | VLAN | Purdue | Criticality | SL-C | Protocols |", "|---|---|---|---|---|---|---|---|---|");
  for (const a of assets) {
    L.push(`| ${md(a.data.title)} | ${a.data.assetType} | ${md(zonePath(model, a.zoneId))} | ${md(a.data.ip)} | ${md(a.data.vlan)} | ${a.data.purdueLevel !== undefined ? "L" + a.data.purdueLevel : "—"} | ${a.data.criticality} | ${md(a.data.slCapability)} | ${md(a.data.protocols.join(", "))} |`);
  }
  L.push("", "> This report describes modelled architecture metadata and automated design checks. It isn't a security assessment, safety case or compliance determination.", "");
  return L.join("\n");
}
